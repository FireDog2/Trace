import type { SkillCandidate } from "../types";
export function SkillCandidatePanel({
  candidate,
  onDecision,
}: {
  candidate: SkillCandidate;
  onDecision(id: string, approved: boolean): Promise<void>;
}) {
  return (
    <section className="skill-candidate" aria-label="Skill candidate">
      <header>
        <span className="section-label">
          {candidate.candidate_type === "failure_review"
            ? "FAILURE REVIEW CANDIDATE"
            : "SKILL CANDIDATE"}
        </span>
        <h3>
          {candidate.name} v{candidate.version}
          {candidate.candidate_type === "failure_review"
            ? " · Failure review"
            : ""}
        </h3>
      </header>
      <p>
        Generated by {candidate.generated_by_model} from the current run. It
        remains disabled after static validation and is never enabled
        automatically.
      </p>
      <pre>{candidate.markdown}</pre>
      {candidate.status === "candidate" ? (
        <div>
          <button
            className="primary-action"
            onClick={() => void onDecision(candidate.id, true)}
          >
            {candidate.candidate_type === "failure_review"
              ? "Approve review candidate"
              : "Approve skill candidate"}
          </button>
          <button onClick={() => void onDecision(candidate.id, false)}>
            {candidate.candidate_type === "failure_review"
              ? "Reject review candidate"
              : "Reject skill candidate"}
          </button>
        </div>
      ) : (
        <strong>
          {candidate.status === "approved"
            ? "Approved, still disabled"
            : "Rejected"}
        </strong>
      )}
    </section>
  );
}
